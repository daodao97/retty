// Count is authoritative: the CLI may return only some detail rows, or none.
// A nil Credits slice means unavailable details; an empty slice is a known list.
type ResetCredits struct {
	Count   int         `json:"availableCount"`
	Credits []ResetCard `json:"credits"`
}

type ResetCard struct {
	ID        string `json:"id"`
	Type      string `json:"resetType"`
	Status    string `json:"status"`
	ExpiresAt *int64 `json:"expiresAt"`
}

func (r *ResetCredits) normalize(now time.Time) {
	r.Count = max(0, r.Count)
	if r.Credits == nil {
		return
	}
	kept := make([]ResetCard, 0, len(r.Credits))
	seen := map[string]bool{}
	for _, card := range r.Credits {
		if card.ID == "" || seen[card.ID] || card.Status != "available" || card.Type != "codexRateLimits" || card.ExpiresAt != nil && *card.ExpiresAt <= now.Unix() {
			continue
		}
		seen[card.ID] = true
		kept = append(kept, card)
	}
	slices.SortStableFunc(kept, func(a, b ResetCard) int {
		if a.ExpiresAt == nil {
			if b.ExpiresAt == nil {
				return 0
			}
			return 1
		}
		if b.ExpiresAt == nil {
			return -1
		}
		return time.Unix(*a.ExpiresAt, 0).Compare(time.Unix(*b.ExpiresAt, 0))
	})
	r.Credits = kept
}

// ResetAttempt identifies one confirmed logical use, including retries after
// an ambiguous network failure. It is never generated by polling.
type ResetAttempt struct {
	Key, CreditID, AccountKey, Home string
}

func NewResetAttempt(r Reading) (ResetAttempt, error) {
	if r.Agent != "codex" || r.Resets == nil || r.Resets.Count <= 0 {
		return ResetAttempt{}, errors.New("当前账户没有可用重置卡，请先刷新")
	}
	if r.AccountKey == "" || r.Home == "" {
		return ResetAttempt{}, errors.New("CLI 未提供账户标识，请更新 Codex 后刷新")
	}
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return ResetAttempt{}, errors.New("无法创建用卡操作，请重试")
	}
	b[6], b[8] = b[6]&0x0f|0x40, b[8]&0x3f|0x80
	a := ResetAttempt{Key: fmt.Sprintf("%x-%x-%x-%x-%x", b[:4], b[4:6], b[6:8], b[8:10], b[10:]), AccountKey: r.AccountKey, Home: r.Home}
	// Name the soonest card only when all counted cards are listed. Otherwise
	// leave selection to Codex rather than claim an incomplete list is complete.
	if len(r.Resets.Credits) == r.Resets.Count {
		cards := *r.Resets
		cards.normalize(time.Now())
		if len(cards.Credits) == cards.Count {
			a.CreditID = cards.Credits[0].ID
		}
	}
	return a, nil
}

type ResetResult struct {
	Outcome string
	Reading Reading
}

func UseCodexReset(ctx context.Context, attempt ResetAttempt) (ResetResult, error) {
	binary, err := findBinary("codex")
	if err != nil {
		return ResetResult{}, errors.New("未找到 codex 命令")
	}
	home, err := agents.ConfigDir("codex")
	if err != nil || home != attempt.Home {
		return ResetResult{}, errors.New("Codex 配置目录已变化，请刷新后重新确认")
	}
	return useCodexReset(ctx, binary, home, attempt)
}

func useCodexReset(ctx context.Context, binary, home string, attempt ResetAttempt) (ResetResult, error) {
	if attempt.Key == "" || attempt.AccountKey == "" || attempt.Home != home {
		return ResetResult{}, errors.New("用卡操作缺少账户确认，请刷新后重试")
	}
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	var out ResetResult
	err := withCodex(ctx, binary, home, func(rpc *codexRPC) error {
		current, err := rpc.read()
		if err != nil {
			return err
		}
		if current.AccountKey != attempt.AccountKey {
			return errors.New("Codex 登录账户已变化，未使用重置卡；请刷新后重新确认")
		}
		params := map[string]string{"idempotencyKey": attempt.Key}
		if attempt.CreditID != "" {
			params["creditId"] = attempt.CreditID
		}
		// Send exactly once. Even a zero count may mean an earlier, timed-out
		// use succeeded: its same idempotency key resolves that outcome safely.
		if err := rpc.call("account/rateLimitResetCredit/consume", params, &out); err != nil {
			return errors.New("用卡结果尚未确认，请刷新查看或重试同次操作；旧版 CLI 可能不支持用卡")
		}
		switch out.Outcome {
		case "reset", "alreadyRedeemed", "nothingToReset", "noCredit":
		default:
			return errors.New("无法确认用卡结果，请刷新查看或重试同次操作")
		}
		out.Reading, err = rpc.read()
		if err != nil {
			out.Reading = Reading{Agent: "codex", At: time.Now(), Error: "用卡结果已确认，额度读取失败，请刷新"}
		}
		return nil
	})
	if err != nil && ctx.Err() != nil {
		err = errors.New("用卡请求超时，结果尚未确认，请刷新查看或重试同次操作")
	}
	return out, err
}
